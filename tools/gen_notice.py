#!/usr/bin/env python3
"""Generate src/notice_glyph.h: the low battery icon as an 8-bit coverage
mask, cropped to what it covers. The plugin blends the icon in red over
whatever is on screen.

The icon is the XMB battery icon, copied pixel by pixel from a screenshot of
the XMB and emptied of its bars. It goes back where it was found, so in the
XMB it lands exactly on the stock one. tools/xmb_battery.png is that corner
of the screenshot.

The HOME screen has an icon of its own, drawn a little differently, so it
gets a second mask of the same size and place. tools/impose_battery.png is
that icon with no bars: the fourth 28x17 frame of the first sprite set in
flash0:/kd/resource/impose.rsc (6.61), which impose copies to 450,5.

usage: gen_notice.py OUT.h"""
import os
import sys
from PIL import Image, ImageChops

CROP = os.path.join(os.path.dirname(__file__), "xmb_battery.png")
CROP_X, CROP_Y = 450, 5		# where the crop was on screen
BARS_BOX = (456, 9, 472, 16)	# the charge bars, on screen
# The XMB background has this much more blue than red, lit or in the icon's
# shadow; the icon is white and takes it away in proportion to its coverage.
BG_TINT = 15

HOME_CROP = os.path.join(os.path.dirname(__file__), "impose_battery.png")
HOME_X, HOME_Y = 450, 5		# where impose puts its sprite
# The sprite is opaque, 5 bits of grey: white icon on this much background.
HOME_BG = 7
HOME_WHITE = 31


def coverage():
    """Icon coverage, and where it goes on screen."""
    r, _, b = Image.open(CROP).convert("RGB").split()
    tint = ImageChops.subtract(b, r)
    # one step of tint is the noise floor
    a = tint.point(lambda v: 0 if v >= BG_TINT - 1 else round((BG_TINT - v) * 255 / BG_TINT))
    x0, y0, x1, y1 = BARS_BOX
    a.paste(0, (x0 - CROP_X, y0 - CROP_Y, x1 - CROP_X, y1 - CROP_Y))
    box = a.getbbox()
    return a.crop(box), (CROP_X + box[0], CROP_Y + box[1])


def home_coverage(size, pos):
    """Coverage of the HOME screen icon, in the box of the XMB one."""
    v = Image.open(HOME_CROP).convert("L").point(lambda p: p >> 3)
    # one step over the background is the noise floor
    a = v.point(lambda p: 0 if p <= HOME_BG + 1
                else round((p - HOME_BG) * 255 / (HOME_WHITE - HOME_BG)))
    x0, y0 = pos[0] - HOME_X, pos[1] - HOME_Y
    box = (x0, y0, x0 + size[0], y0 + size[1])
    out = a.copy()
    out.paste(0, box)
    if out.getbbox():
        sys.exit("HOME screen icon does not fit the XMB icon's box")
    return a.crop(box)


def emit(f, name, im):
    w, h = im.size
    px = im.tobytes()
    f.write("static const u8 %s[NOTICE_W * NOTICE_H] = {\n" % name)
    for y in range(h):
        f.write("\t" + " ".join("0x%02X," % p for p in px[y * w:(y + 1) * w]) + "\n")
    f.write("};\n")


def show(im):
    w, h = im.size
    px = im.tobytes()
    for row in range(h):
        print("".join(" .:-=+*#%@"[p * 9 // 255] for p in px[row * w:(row + 1) * w]))


def main():
    a, (x, y) = coverage()
    w, h = a.size
    home = home_coverage(a.size, (x, y))

    with open(sys.argv[1], "w") as f:
        f.write("/* Generated by tools/gen_notice.py, do not edit. */\n\n")
        f.write("#define NOTICE_W\t%d\n#define NOTICE_H\t%d\n" % (w, h))
        f.write("/* where the mask goes on screen */\n")
        f.write("#define NOTICE_X\t%d\n#define NOTICE_Y\t%d\n\n" % (x, y))
        emit(f, "notice_alpha", a)
        f.write("\n/* the same for the HOME screen's icon */\n")
        emit(f, "home_alpha", home)
    show(a)
    show(home)
    print("%dx%d at %d,%d" % (w, h, x, y))


if __name__ == "__main__":
    main()
