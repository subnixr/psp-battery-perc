#!/usr/bin/env python3
"""Generate src/percent_glyph.h: a '%' sprite in the style of the impose.rsc
clock digits (16x15, ABGR1555 grey, white glyph, soft drop shadow, flat
background). Two copies: glyph at column 0 and pre-shifted by one pixel, as
impose keeps for its own digits (its blit needs an even x)."""
import sys
from PIL import Image, ImageDraw, ImageFilter, ImageChops

W, H, SS = 16, 15, 8
BG, FG = 7, 31


def coverage():
    im = Image.new("L", (W * SS, H * SS), 0)
    d = ImageDraw.Draw(im)
    s = SS

    def ring(cx, cy, r, t):
        d.ellipse([(cx - r) * s, (cy - r) * s, (cx + r) * s, (cy + r) * s], fill=255)
        d.ellipse([(cx - r + t) * s, (cy - r + t) * s, (cx + r - t) * s, (cy + r - t) * s], fill=0)

    ring(2.9, 3.9, 2.9, 1.5)
    ring(8.1, 10.1, 2.9, 1.5)
    d.line([(8.9 * s, 1.3 * s), (2.1 * s, 12.7 * s)], fill=255, width=int(1.6 * s))
    return im.resize((W, H), Image.BOX)


def sprite(shift):
    a = ImageChops.offset(coverage(), shift, 0)
    sh = ImageChops.offset(a, 2, 2).filter(ImageFilter.GaussianBlur(0.8))
    out = []
    for y in range(H):
        for x in range(W):
            av = a.getpixel((x, y)) / 255.0
            sv = min(1.0, sh.getpixel((x, y)) / 255.0 * 1.3)
            v = round((BG - 4.5 * sv) * (1 - av) + FG * av)
            v = max(2, min(31, v))
            out.append(0x8000 | v << 10 | v << 5 | v)
    return out


def emit(f, name, px):
    f.write("static const u16 %s[16 * 15] __attribute__((aligned(16))) = {\n" % name)
    for y in range(H):
        f.write("\t" + " ".join("0x%04X," % p for p in px[y * W:(y + 1) * W]) + "\n")
    f.write("};\n\n")


def main():
    with open(sys.argv[1], "w") as f:
        f.write("/* Generated by tools/gen_percent.py, do not edit. */\n\n")
        emit(f, "percent_even", sprite(0))
        emit(f, "percent_odd", sprite(1))
    px = sprite(0)
    for y in range(H):
        print(" ".join(".." if (p & 31) == BG else "%2d" % (p & 31) for p in px[y * W:(y + 1) * W]))


if __name__ == "__main__":
    main()
